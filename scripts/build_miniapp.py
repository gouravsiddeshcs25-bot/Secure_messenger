"""
Builds frontend/telegram-miniapp/index.html from frontend/web/index.html.

The Mini App IS the v2 messenger (same chat screen, same crypto, same JavaScript modules). Only two things differ:
- the sign-in screen (Telegram login + a PIN instead of username + password), and
- it loads Telegram's official script and its own start-up module.
Copying the page with a script keeps the two in sync. Run it after changing frontend/web/index.html:

    python scripts\\build_miniapp.py
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "frontend", "web", "index.html")
DST = os.path.join(ROOT, "frontend", "telegram-miniapp", "index.html")
AUTH = os.path.join(ROOT, "frontend", "telegram-miniapp", "auth.html")

AUTH_START = "    <!-- ================= Sign in ================= -->"
AUTH_END = "    <!-- ================= App ================= -->"


def swap(html: str, old: str, new: str) -> str:
    if html.count(old) != 1:
        raise SystemExit(f"build_miniapp: expected exactly one {old!r} in frontend/web/index.html")
    return html.replace(old, new)


def main():
    with open(SRC, encoding="utf-8") as f:
        html = f.read()
    with open(AUTH, encoding="utf-8") as f:
        auth = f.read().rstrip("\n") + "\n\n"

    start, end = html.index(AUTH_START), html.index(AUTH_END)
    html = html[:start] + auth + html[end:]

    html = swap(html, "<title>Secure Messenger</title>", "<title>CipherBridge</title>")
    html = swap(html, '<link rel="stylesheet" href="app.css">',
                '<link rel="stylesheet" href="/v2/app.css">\n    <link rel="stylesheet" href="miniapp.css">')
    # Telegram's official Mini App script is the only external script allowed (see the telegram-miniapp skill).
    html = swap(html, '    <script src="/shared/vendor/libsodium.js"></script>',
                '    <script src="https://telegram.org/js/telegram-web-app.js"></script>\n'
                '    <script src="/shared/vendor/libsodium.js"></script>')
    html = swap(html, '<script type="module" src="js/app.js"></script>', '<script type="module" src="app.js"></script>')
    banner = "<!-- GENERATED by scripts/build_miniapp.py from frontend/web/index.html. Edit those, not this file. -->\n"

    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(banner + html)
    print("wrote", os.path.relpath(DST, ROOT))


if __name__ == "__main__":
    main()
